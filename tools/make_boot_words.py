#!/usr/bin/env python3
"""Write the panel firmware's built-in boot screen wording
(firmware/components/room_tiles/boot_words.h) from the dashboard's wording
(frontend/i18n/<lang>.json).

A new panel has no wording pack yet - HA sends it once the panel is added -
so the texts it shows before that (Wi-Fi setup, "Add this panel in Home
Assistant", connecting, downloads) are built into the firmware, in every
language, for the language picked on its first start. A stored pack still
comes first (the firmware's boot_text_).

    tools/make_boot_words.py           # write the header
    tools/make_boot_words.py --check   # exit 1 when it isn't current (tests)
"""

from __future__ import annotations

import ast
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
I18N = ROOT / "frontend" / "i18n"
PANELS = ROOT / "custom_components" / "room_tiles" / "panels.py"
HEADER = ROOT / "firmware" / "components" / "room_tiles" / "boot_words.h"

# every boot screen line the firmware says before it has a pack
KEYS = [
    "panel.add_title",
    "panel.add_where",
    "panel.cant_reach",
    "panel.factory_reset",
    "panel.connecting",
    "panel.getting_data",
    "panel.getting_wording",
    "panel.needs_firmware",
    "panel.needs_integration",
    "panel.not_accepted",
    "panel.not_answering",
    "panel.theme_downloading",
    "panel.theme_requesting",
    "panel.theme_saving",
    "panel.unreadable",
    "panel.update_downloading",
    "panel.update_installing",
    "panel.update_restarting",
    "panel.wait_added",
    "panel.wait_time",
    "panel.wifi_change",
    "panel.wifi_change_again",
    "panel.wifi_chip_updating",
    "panel.wifi_setup",
    # Wi-Fi set up on the panel (wifi_setup.cpp) - before it ever had a pack
    "common.back",
    "common.cancel",
    "panel.wifi_again",
    "panel.wifi_connect",
    "panel.wifi_change_ask",
    "panel.wifi_connected",
    "screen.restart",
    "panel.wifi_connecting_to",
    "panel.wifi_failed",
    "panel.wifi_kept",
    "panel.wifi_looking",
    "panel.wifi_name_ask",
    "panel.wifi_none",
    "panel.wifi_other",
    "panel.wifi_password_for",
    "panel.wifi_phone_hint",
    "panel.wifi_phone_instead",
    "panel.wifi_pick",
]


def lang_names() -> dict[str, str]:
    """Each language's own name, in Room Tiles' order (panels.py LANG_NAMES)."""
    for node in ast.parse(PANELS.read_text(encoding="utf-8")).body:
        if isinstance(node, ast.Assign) and any(getattr(t, "id", None) == "LANG_NAMES" for t in node.targets):
            return ast.literal_eval(node.value)
    raise SystemExit("LANG_NAMES not found in panels.py")


def c_str(s: str) -> str:
    """A C++ string literal (UTF-8 as it is)."""
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def header() -> str:
    names = lang_names()
    tables = {code: json.loads((I18N / f"{code}.json").read_text(encoding="utf-8"))["strings"] for code in names}
    english = tables["en"]
    missing = [k for k in KEYS if k not in english]
    if missing:
        raise SystemExit(f"not in en.json: {', '.join(missing)}")
    out = [
        "// GENERATED by tools/make_boot_words.py from frontend/i18n - don't edit.",
        "// The boot screen's wording before the panel has a pack (a new panel):",
        "// in every language, for the one picked on its first start.",
        "#pragma once",
        "",
        "#include <cstring>",
        "",
        "namespace esphome::room_tiles {",
        "",
        f"static constexpr int BOOT_LANG_COUNT = {len(names)};",
        f"static constexpr int BOOT_KEY_COUNT = {len(KEYS)};",
        "",
        "// language codes, and each one's name in itself (the language picker)",
        "static const char *const BOOT_LANGS[BOOT_LANG_COUNT] = {" + ", ".join(c_str(c) for c in names) + "};",
        "static const char *const BOOT_LANG_NAMES[BOOT_LANG_COUNT] = {"
        + ", ".join(c_str(n) for n in names.values())
        + "};",
        "",
        "static const char *const BOOT_KEYS[BOOT_KEY_COUNT] = {",
    ]
    out += [f"    {c_str(k)}," for k in KEYS]
    out += ["};", "", "// [language][key] (a missing translation: the English text)",
            "static const char *const BOOT_WORDS[BOOT_LANG_COUNT][BOOT_KEY_COUNT] = {"]
    for code in names:
        out.append(f"    {{  // {code}")
        out += [f"        {c_str(tables[code].get(k) or english[k])}," for k in KEYS]
        out.append("    },")
    out += [
        "};",
        "",
        "/// A language's index (-1: not built in).",
        "inline int boot_lang_index(const char *code) {",
        "  for (int i = 0; i < BOOT_LANG_COUNT; i++)",
        "    if (std::strcmp(BOOT_LANGS[i], code) == 0)",
        "      return i;",
        "  return -1;",
        "}",
        "",
        "/// `key` in language `lang` (English when that language isn't built in);",
        "/// nullptr for a key that isn't a boot screen line.",
        "inline const char *boot_word(const char *lang, const char *key) {",
        "  int l = boot_lang_index(lang);",
        "  if (l < 0)",
        "    l = 0;",
        "  for (int k = 0; k < BOOT_KEY_COUNT; k++)",
        "    if (std::strcmp(BOOT_KEYS[k], key) == 0)",
        "      return BOOT_WORDS[l][k];",
        "  return nullptr;",
        "}",
        "",
        "}  // namespace esphome::room_tiles",
        "",
    ]
    return "\n".join(out)


def main() -> int:
    text = header()
    if "--check" in sys.argv[1:]:
        current = HEADER.read_text(encoding="utf-8") if HEADER.exists() else ""
        if current != text:
            print(f"{HEADER.relative_to(ROOT)} is out of date: run tools/make_boot_words.py")
            return 1
        return 0
    HEADER.write_text(text, encoding="utf-8")
    print(f"wrote {HEADER.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
